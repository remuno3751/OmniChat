#!/usr/bin/env bash
# Builds the Windows artifacts of a release on this PC (Git Bash) and uploads them to the release of the tag:
# server app (NSIS), desktop client (NSIS + MSI), server bundle zip. No CI minutes needed.
#   packaging/local/build-windows.sh v0.2.0            # build + upload
#   packaging/local/build-windows.sh v0.2.0 --no-upload
# The version stamps (tauri.conf.json / Cargo.toml / Cargo.lock) are restored afterwards with `git checkout`: COMMIT your changes to those
# files first, or they are lost.
set -euo pipefail
TAG="${1:?usage: build-windows.sh <tag> [--no-upload]}"
VER="${TAG#v}"
cd "$(dirname "$0")/../.."
restore() { git checkout -- server-app/src-tauri/Cargo.toml server-app/src-tauri/tauri.conf.json server-app/src-tauri/Cargo.lock desktop/src-tauri/Cargo.toml desktop/src-tauri/tauri.conf.json desktop/src-tauri/Cargo.lock 2>/dev/null || true; }
trap restore EXIT
# Keep this PC's account name out of the binaries (Rust panic locations carry the cargo registry path): remap the home and repo folders.
export RUSTFLAGS="${RUSTFLAGS:-} --remap-path-prefix=$(cygpath -w "$HOME")=C:\build --remap-path-prefix=$(cygpath -w "$PWD")=."
OUT="${OMNICHAT_OUT:-out-windows}"; rm -rf "$OUT"; mkdir -p "$OUT"

# a leftover app/android (generated by build-android.sh) makes `expo export --platform web` fail with "No platforms are configured"
rm -rf app/android
echo "== server app"
node desktop/tools/set-version.mjs "$TAG" server-app
OMNICHAT_VERSION="$VER" node server-app/tools/prepare-bundle.mjs > /dev/null   # the bundled server reports the release version, not server/package.json's
(cd server-app && npx tauri build --bundles nsis)   # not msi: WiX fails on the Japanese strings (codepage 1252)
S="$(ls -t server-app/src-tauri/target/release/bundle/nsis/*_x64-setup.exe | head -1)"
cp "$S" "$OUT/OmniChat-Server-App-$TAG-Windows-x64-Setup.exe"; cp "$S" "$OUT/OmniChat-Server-App-Windows-x64-Setup.exe"

node packaging/local/scan-leaks.mjs server-app/src-tauri/target/release/*.exe
echo "== desktop"
node desktop/tools/set-version.mjs "$TAG" desktop
(cd desktop && npm ci --no-audit --no-fund > /dev/null && npx tauri build --bundles nsis,msi)
D="$(ls -t desktop/src-tauri/target/release/bundle/nsis/*_x64-setup.exe | head -1)"
M="$(ls -t desktop/src-tauri/target/release/bundle/msi/*.msi | head -1)"
cp "$D" "$OUT/OmniChat-Desktop-$TAG-Windows-x64-Setup.exe"; cp "$D" "$OUT/OmniChat-Desktop-Windows-x64-Setup.exe"
cp "$M" "$OUT/OmniChat-Desktop-$TAG-Windows-x64.msi";      cp "$M" "$OUT/OmniChat-Desktop-Windows-x64.msi"

node packaging/local/scan-leaks.mjs desktop/src-tauri/target/release/*.exe
echo "== server bundle zip"
rm -rf .release/stage
node packaging/build-release.mjs --out .release/stage --version "$VER"
node packaging/make-bundle-zip.mjs .release/stage/server "$OUT/omnichat-server-bundle-$VER.zip"

echo "== DSH plugin (.tgz)"
(cd dsh-plugin && npm pack --pack-destination "../$OUT" > /dev/null)

(cd "$OUT" && sha256sum omnichat-dsh-bridge-*.tgz > SHA256SUMS-tools.txt && sha256sum OmniChat-Server-App-*.exe > SHA256SUMS-server-app.txt && sha256sum OmniChat-Desktop-* > SHA256SUMS-desktop.txt && sha256sum omnichat-server-bundle-*.zip > SHA256SUMS-bundle.txt)
ls -l "$OUT"
[ "${2:-}" = "--no-upload" ] || node packaging/local/upload.mjs "$TAG" "$OUT"/*
