import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const watch = process.argv.includes("--watch");

// Shared Node-only git helpers (docs/design/VSCODE-BRIDGE.md §1.6); bundled, not copied.
const gitopsAlias = fileURLToPath(new URL("../bridge/src/gitops.ts", import.meta.url));
// Pure modules shared with the OmniChat app (markdownParse, highlight); bundled, not copied.
const appAlias = fileURLToPath(new URL("../app/src", import.meta.url));

const options = {
  entryPoints: ["src/extension.ts"],
  bundle: true,
  outfile: "dist/extension.js",
  platform: "node",
  format: "cjs",
  target: "node18",
  external: ["vscode"],
  sourcemap: true,
  logLevel: "info",
  alias: { "@gitops": gitopsAlias },
};

// Webview bundles (run in the browser sandbox). Each entry is built only when its source exists,
// so this step is a no-op until the webview sources are added.
const webviewEntries = [{ in: "src/webview/chat/main.ts", out: "media/webview/chat.js" }];

const webviewOptions = webviewEntries
  .filter((e) => existsSync(e.in))
  .map((e) => ({
    entryPoints: [e.in],
    bundle: true,
    outfile: e.out,
    platform: "browser",
    format: "iife",
    target: "es2020",
    alias: { "@app": appAlias },
    sourcemap: false,
    minify: false,
    logLevel: "info",
    banner: { js: "/* Generated by esbuild.mjs from src/webview. Do not edit. */" },
  }));

if (watch) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  for (const o of webviewOptions) {
    const wctx = await esbuild.context(o);
    await wctx.watch();
  }
} else {
  await esbuild.build(options);
  for (const o of webviewOptions) {
    await esbuild.build(o);
  }
}
