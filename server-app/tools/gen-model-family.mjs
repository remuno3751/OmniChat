// Regenerates ui/vendor/model-family.js (window.OCFamily: resolveFamily + MARK_PATHS) from the app's pure model-name -> badge matching,
// so the server app shows the same model badges as the chat model picker. Run after changing app/src/components/modelFamily.ts or modelLogoData.ts:
//   node server-app/tools/gen-model-family.mjs
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(path.join(root, "server/package.json"));
const esbuild = require("esbuild");
const stub = `import { resolveFamily } from ${JSON.stringify(path.join(root, "app/src/components/modelFamily.ts"))};
import { MARK_PATHS } from ${JSON.stringify(path.join(root, "app/src/components/modelLogoData.ts"))};
window.OCFamily = { resolveFamily, MARK_PATHS };`;
await esbuild.build({
  stdin: { contents: stub, resolveDir: root, loader: "ts" },
  bundle: true, format: "iife", target: "es2019", minify: true, legalComments: "none",
  banner: { js: "/* generated by server-app/tools/gen-model-family.mjs - do not edit */" },
  outfile: path.join(root, "server-app/ui/vendor/model-family.js"),
});
console.log("wrote server-app/ui/vendor/model-family.js");
